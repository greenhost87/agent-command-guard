// Command policygen generates embedded policy tables.
package main

import (
	"encoding/json"
	"fmt"
	"os"
	"strconv"
	"strings"
)

type interpreterPolicy struct {
	Pipe           []string `json:"pipe"`
	Node           []string `json:"node"`
	PythonPrefixes []string `json:"python_prefixes"`
	Shell          []string `json:"shell"`
}

type messagePolicy struct {
	ScriptDir               string `json:"script_dir"`
	ScriptGuidance          string `json:"script_guidance"`
	TranscriptsMarker       string `json:"transcripts_marker"`
	TranscriptsReason       string `json:"transcripts_reason"`
	QualityGateMarker       string `json:"quality_gate_marker"`
	QualityGateToken        string `json:"quality_gate_token"`
	QualityGateReason       string `json:"quality_gate_reason"`
	InteractiveReasonPrefix string `json:"interactive_reason_prefix"`
	ProtectedReason         string `json:"protected_reason"`
}

type policyConfig struct {
	Separators     []string          `json:"separators"`
	ShellKeywords  []string          `json:"shell_keywords"`
	Wrappers       []string          `json:"wrappers"`
	ShellToolNames []string          `json:"shell_tool_names"`
	PatchToolNames []string          `json:"patch_tool_names"`
	RemoteCommands []string          `json:"remote_commands"`
	Interpreters   interpreterPolicy `json:"interpreters"`
	Messages       messagePolicy     `json:"messages"`
	ScanTriggers   []string          `json:"scan_triggers"`
	ProtectedPaths []string          `json:"protected_paths"`
}

func fallback(value, fallback string) string {
	if value != "" {
		return value
	}
	return fallback
}

func emitSlice(output *strings.Builder, name string, values []string) {
	fmt.Fprintf(output, "var %s = []string{\n", name)
	for _, value := range values {
		fmt.Fprintf(output, "\t%s,\n", strconv.Quote(value))
	}
	output.WriteString("}\n\n")
}

func emitConst(output *strings.Builder, name, value string) {
	fmt.Fprintf(output, "const %s = %s\n", name, strconv.Quote(value))
}

func main() {
	raw, err := os.ReadFile("config/policy.json")
	if err != nil {
		panic(err)
	}
	var config policyConfig
	if err := json.Unmarshal(raw, &config); err != nil {
		panic(err)
	}
	messages := config.Messages
	scriptGuidance := fallback(messages.ScriptGuidance, "If temporary code is needed, create a readable script under `.codex/tmp-scripts/` in the current project/workspace, run it as a file, and leave it in place for audit.")
	interactivePrefix := messages.InteractiveReasonPrefix
	if interactivePrefix == "" {
		interactivePrefix = "Blocked interactive interpreter session. PTY input bypasses PreToolUse inspection. "
	}
	protectedPathsLower := make([]string, len(config.ProtectedPaths))
	for index, path := range config.ProtectedPaths {
		protectedPathsLower[index] = strings.ToLower(path)
	}

	var output strings.Builder
	output.WriteString("// Code generated by go generate from config/policy.json; DO NOT EDIT.\n\npackage main\n\n")
	emitSlice(&output, "generatedSeparators", config.Separators)
	emitSlice(&output, "generatedKeywords", config.ShellKeywords)
	emitSlice(&output, "generatedWrappers", config.Wrappers)
	emitSlice(&output, "generatedShellTools", config.ShellToolNames)
	emitSlice(&output, "generatedPatchTools", config.PatchToolNames)
	emitSlice(&output, "generatedRemote", config.RemoteCommands)
	emitSlice(&output, "generatedPipe", config.Interpreters.Pipe)
	emitSlice(&output, "generatedNode", config.Interpreters.Node)
	emitSlice(&output, "generatedShellInterpreters", config.Interpreters.Shell)
	emitSlice(&output, "generatedPythonPrefixes", config.Interpreters.PythonPrefixes)
	emitSlice(&output, "generatedScanTriggers", config.ScanTriggers)
	emitSlice(&output, "generatedProtectedPaths", config.ProtectedPaths)
	emitSlice(&output, "generatedProtectedPathsLower", protectedPathsLower)
	emitConst(&output, "generatedScriptDir", fallback(messages.ScriptDir, ".codex/tmp-scripts"))
	emitConst(&output, "generatedScriptGuidance", scriptGuidance)
	emitConst(&output, "generatedTranscriptsMarker", fallback(messages.TranscriptsMarker, "agent-transcripts"))
	emitConst(&output, "generatedTranscriptsReason", fallback(messages.TranscriptsReason, "Blocked access to agent-transcripts."))
	emitConst(&output, "generatedQualityGateMarker", fallback(messages.QualityGateMarker, "/.agent-quality-gate"))
	emitConst(&output, "generatedQualityGateToken", fallback(messages.QualityGateToken, "agent-quality-gate"))
	emitConst(&output, "generatedQualityGateReason", fallback(messages.QualityGateReason, "Blocked access to ~/.agent-quality-gate/ outside the agent-quality-gate project."))
	emitConst(&output, "generatedProtectedReason", fallback(messages.ProtectedReason, "Blocked modification of the agent-command-guard policy configuration. Enforcement policy must stay under explicit review; edit this file manually outside agent tools if needed."))
	emitConst(&output, "generatedInlineInterpreterReason", "Blocked inline interpreter code. "+scriptGuidance)
	emitConst(&output, "generatedStdinInterpreterReason", "Blocked interpreter code from stdin/heredoc. "+scriptGuidance)
	emitConst(&output, "generatedInteractiveInterpreterReason", interactivePrefix+scriptGuidance)

	if err := os.WriteFile("policy_tables_gen.go", []byte(output.String()), 0o644); err != nil {
		panic(err)
	}
}
